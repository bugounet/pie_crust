//! Commands run only after an explicit user action, in the selected worktree.
//! Streaming run logs and persistent line-oriented shells share the bottom panel.

use eframe::egui::{self, RichText};
use pie_crust_core::{PythonProjectLayout, discover_python_environment};
use serde::{Deserialize, Serialize};
use std::collections::VecDeque;
use std::fs;
use std::io::{Read, Write};
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::sync::mpsc::{self, Receiver, Sender, SyncSender};
use std::thread::{self, JoinHandle};
use std::time::{Duration, Instant};

#[path = "terminal.rs"]
mod terminal;

const OUTPUT_LIMIT: usize = 1024 * 1024;
const HISTORY_LIMIT: usize = 24;

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub(super) enum BottomView {
    Terminal,
    Tests,
    #[default]
    Run,
}

/// A click captures its target before the desktop saves and synchronizes documents.
#[derive(Clone, Debug)]
pub(super) struct RunRequest {
    pub name: String,
    pub command: String,
    pub view: BottomView,
    pub worktree_id: String,
    pub root: PathBuf,
    pub terminal_id: Option<u64>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
struct RunConfig {
    name: String,
    command: String,
    #[serde(default)]
    view: BottomView,
    /// Relative to the selected worktree. Older/custom configurations keep its root.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    working_directory: Option<PathBuf>,
    /// Refresh only commands that still match the value generated by discovery.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    generated_command: Option<String>,
}

#[derive(Serialize, Deserialize)]
struct ConfigFile {
    version: u32,
    configurations: Vec<RunConfig>,
}

pub(super) struct RunPanel {
    config_path: PathBuf,
    worktree_id: String,
    worktree_root: PathBuf,
    source_roots: Vec<PathBuf>,
    primary_source_root: PathBuf,
    configurations: Vec<RunConfig>,
    selected_config: usize,
    popup_open: bool,
    focus_command: bool,
    edit_name: String,
    edit_command: String,
    edit_view: BottomView,
    terminal_command: String,
    sessions: Vec<RunSession>,
    selected_session: Option<u64>,
    next_session: u64,
    error: Option<String>,
    requested_view: Option<BottomView>,
    run_requests: VecDeque<RunRequest>,
    terminals: terminal::Terminals,
}

impl RunPanel {
    pub(super) fn active_terminal_selection(&self, ctx: &egui::Context) -> Option<String> {
        self.terminals.active_selection(ctx)
    }

    pub(super) fn new(project_root: PathBuf) -> Self {
        let config_path = project_root.join(".pie_crust/run-configs.json");
        let (source_roots, primary_source_root) = discover_source_roots(&project_root);
        let (mut configurations, error) = match read_configs(&config_path) {
            Ok(Some(configurations)) => (configurations, None),
            Ok(None) => (default_configs(&project_root, &primary_source_root), None),
            Err(error) => (
                default_configs(&project_root, &primary_source_root),
                Some(format!("Configurations de lancement : {error}")),
            ),
        };
        refresh_generated_configs(
            &mut configurations,
            &project_root,
            &primary_source_root,
            &source_roots,
        );
        let mut panel = Self {
            config_path,
            worktree_id: String::new(),
            worktree_root: project_root,
            source_roots,
            primary_source_root,
            configurations,
            selected_config: 0,
            popup_open: false,
            focus_command: false,
            edit_name: String::new(),
            edit_command: String::new(),
            edit_view: BottomView::Run,
            terminal_command: String::new(),
            sessions: Vec::new(),
            selected_session: None,
            next_session: 1,
            error,
            requested_view: None,
            run_requests: VecDeque::new(),
            terminals: terminal::Terminals::default(),
        };
        panel.load_selected();
        panel
    }

    pub(super) fn set_worktree(&mut self, id: impl Into<String>, root: PathBuf) {
        self.worktree_id = id.into();
        if self.worktree_root != root {
            (self.source_roots, self.primary_source_root) = discover_source_roots(&root);
            self.worktree_root = root;
            self.refresh_configurations();
        }
    }

    /// Capture configuration only; discovery runs when the returned job is called.
    pub(super) fn prepare_worktree(
        &self,
        id: String,
        root: PathBuf,
    ) -> impl FnOnce() -> Self + Send + 'static + use<> {
        let mut prepared = Self {
            config_path: self.config_path.clone(),
            worktree_id: self.worktree_id.clone(),
            worktree_root: self.worktree_root.clone(),
            source_roots: self.source_roots.clone(),
            primary_source_root: self.primary_source_root.clone(),
            configurations: self.configurations.clone(),
            selected_config: self.selected_config,
            popup_open: false,
            focus_command: false,
            edit_name: self.edit_name.clone(),
            edit_command: self.edit_command.clone(),
            edit_view: self.edit_view,
            terminal_command: self.terminal_command.clone(),
            sessions: Vec::new(),
            selected_session: None,
            next_session: 1,
            error: self.error.clone(),
            requested_view: None,
            run_requests: VecDeque::new(),
            terminals: terminal::Terminals::default(),
        };
        move || {
            prepared.set_worktree(id, root);
            prepared
        }
    }

    /// Adopt prepared project data without touching running processes or doing I/O.
    pub(super) fn adopt_project(&mut self, prepared: Self) {
        self.config_path = prepared.config_path;
        self.worktree_id = prepared.worktree_id;
        self.worktree_root = prepared.worktree_root;
        self.source_roots = prepared.source_roots;
        self.primary_source_root = prepared.primary_source_root;
        self.configurations = prepared.configurations;
        self.selected_config = prepared.selected_config;
        self.edit_name = prepared.edit_name;
        self.edit_command = prepared.edit_command;
        self.edit_view = prepared.edit_view;
        self.terminal_command = prepared.terminal_command;
        self.error = prepared.error;
    }

    pub(super) fn open_run_popup(&mut self) {
        self.popup_open = true;
        self.focus_command = true;
    }

    pub(super) fn is_running(&self) -> bool {
        self.terminals.is_running() || self.sessions.iter().any(|session| session.is_running())
    }

    pub(super) fn requested_view(&mut self) -> Option<BottomView> {
        if std::mem::take(&mut self.terminals.requested_view) {
            return Some(BottomView::Terminal);
        }
        self.requested_view.take()
    }

    pub(super) fn open_terminal_drawer(&mut self) {
        self.terminals.open_drawer();
    }

    pub(super) fn take_close_drawer(&mut self) -> bool {
        self.terminals.take_close_drawer()
    }

    pub(super) fn poll(&mut self) -> bool {
        let mut changed = self.terminals.poll();
        for session in &mut self.sessions {
            changed |= session.poll();
        }
        changed
    }

    pub(super) fn run_selected(&mut self) {
        if let Some(configuration) = self.configurations.get(self.selected_config).cloned() {
            self.run_command_in_directory(
                &configuration.name,
                &configuration.command,
                configuration.view,
                configuration.working_directory.as_deref(),
            );
        } else {
            self.open_run_popup();
        }
    }

    pub(super) fn run_command(&mut self, name: &str, command: &str, view: BottomView) {
        self.run_command_in_directory(name, command, view, None);
    }

    fn run_command_in_directory(
        &mut self,
        name: &str,
        command: &str,
        view: BottomView,
        directory: Option<&Path>,
    ) {
        let command = command.trim();
        if command.is_empty() {
            self.error = Some("Saisissez une commande à exécuter.".into());
            return;
        }
        if !self.worktree_root.is_dir() {
            self.error = Some("Le dossier du worktree n’est plus disponible.".into());
            return;
        }
        let command = match command_in_directory(&self.worktree_root, directory, command) {
            Ok(command) => command,
            Err(error) => {
                self.error = Some(error);
                return;
            }
        };
        if self
            .sessions
            .iter()
            .filter(|session| session.is_running())
            .count()
            + self.run_requests.len()
            >= 8
        {
            self.error =
                Some("Arrêtez une exécution avant d’en lancer une autre (8 maximum).".into());
            return;
        }
        self.run_requests.push_back(RunRequest {
            name: name.to_owned(),
            command,
            view,
            worktree_id: self.worktree_id.clone(),
            root: self.worktree_root.clone(),
            terminal_id: None,
        });
        self.requested_view = Some(view);
        self.error = None;
    }

    pub(super) fn take_run_request(&mut self) -> Option<RunRequest> {
        self.run_requests.pop_front()
    }

    pub(super) fn set_launch_error(&mut self, message: impl Into<String>) {
        self.error = Some(message.into());
    }

    /// Called by the desktop only after the requested worktree's buffers were saved.
    pub(super) fn start_request(&mut self, request: RunRequest) -> bool {
        if request.command.trim().is_empty() {
            self.set_launch_error("Saisissez une commande à exécuter.");
            return false;
        }
        if !request.root.is_dir() {
            self.set_launch_error("Le dossier du worktree n’est plus disponible.");
            return false;
        }
        if request.view == BottomView::Terminal {
            match self.terminals.start_request(request) {
                Ok(()) => {
                    self.error = None;
                    return true;
                }
                Err(error) => {
                    self.set_launch_error(error);
                    return false;
                }
            }
        }
        if self
            .sessions
            .iter()
            .filter(|session| session.is_running())
            .count()
            >= 8
        {
            self.set_launch_error("Arrêtez une exécution avant d’en lancer une autre (8 maximum).");
            return false;
        }
        while self.sessions.len() >= HISTORY_LIMIT {
            if let Some(index) = self
                .sessions
                .iter()
                .position(|session| !session.is_running())
            {
                self.sessions.remove(index);
            } else {
                break;
            }
        }
        let id = self.next_session;
        self.next_session += 1;
        self.sessions.push(RunSession::start(
            id,
            request.name,
            request.command,
            request.view,
            request.worktree_id,
            request.root,
        ));
        self.selected_session = Some(id);
        self.requested_view = Some(request.view);
        self.error = None;
        true
    }

    /// `args` is an explicitly selected command fragment, not a filename to interpolate.
    pub(super) fn run_python_command_in_source_root(
        &mut self,
        name: &str,
        args: &str,
        view: BottomView,
        source_root: &Path,
    ) -> bool {
        let command = format!(
            "{} {args}",
            python_interpreter_in_source_root(&self.worktree_root, source_root)
        );
        let pending = self.run_requests.len();
        self.run_command_in_directory(name, &command, view, Some(source_root));
        self.run_requests.len() > pending
    }

    pub(super) fn completed_output_for(
        &self,
        worktree_id: &str,
        name: &str,
    ) -> Option<(u64, bool, &str)> {
        self.sessions
            .iter()
            .rev()
            .find(|session| {
                session.worktree_id == worktree_id && session.name == name && !session.is_running()
            })
            .map(|session| {
                (
                    session.id,
                    session.result == Some((Some(0), false)),
                    session.output.as_str(),
                )
            })
    }

    pub(super) fn command_is_pending_or_running(&self, worktree_id: &str, name: &str) -> bool {
        self.run_requests
            .iter()
            .any(|request| request.worktree_id == worktree_id && request.name == name)
            || self.sessions.iter().any(|session| {
                session.worktree_id == worktree_id && session.name == name && session.is_running()
            })
    }

    pub(super) fn show_run_controls(&mut self, ui: &mut egui::Ui) {
        let name = self
            .configurations
            .get(self.selected_config)
            .map_or("Commande…", |configuration| configuration.name.as_str());
        if ui
            .button(format!("{name}  ▾"))
            .on_hover_text("Configurations de lancement · Ctrl+R")
            .clicked()
        {
            self.open_run_popup();
        }
        if ui
            .button(RichText::new("▶").color(egui::Color32::from_rgb(118, 194, 137)))
            .on_hover_text("Exécuter la configuration sélectionnée")
            .clicked()
        {
            self.run_selected();
        }
        if self.is_running()
            && ui
                .button("■")
                .on_hover_text("Arrêter les commandes en cours")
                .clicked()
        {
            for session in &mut self.sessions {
                session.stop();
            }
            self.terminals.stop_all();
        }
    }

    pub(super) fn show_drawer(&mut self, ui: &mut egui::Ui, view: BottomView) {
        if view == BottomView::Terminal {
            self.terminals
                .show_drawer(ui, &self.worktree_id, &self.worktree_root);
            self.show_error(ui);
            return;
        }
        ui.label(match view {
            BottomView::Terminal => "Console de commandes",
            BottomView::Tests => "Commandes de test",
            BottomView::Run => "Configurations de lancement",
        });
        ui.add_space(6.0);
        if view == BottomView::Terminal {
            ui.label("Exécutez vos commandes dans le worktree actif. Chaque commande démarre un nouveau shell.");
            if ui.button("Ouvrir la console").clicked() {
                self.requested_view = Some(view);
            }
        } else {
            let mut run = None;
            let mut selected = None;
            for (index, configuration) in self.configurations.iter().enumerate() {
                if view == BottomView::Tests && configuration.view != BottomView::Tests {
                    continue;
                }
                ui.horizontal(|ui| {
                    if ui
                        .selectable_label(self.selected_config == index, &configuration.name)
                        .on_hover_text(&configuration.command)
                        .clicked()
                    {
                        selected = Some(index);
                    }
                    if ui.small_button("▶").on_hover_text("Exécuter").clicked() {
                        run = Some(index);
                    }
                });
            }
            if let Some(index) = selected {
                self.selected_config = index;
                self.load_selected();
            }
            if let Some(index) = run {
                self.selected_config = index;
                self.load_selected();
                self.run_selected();
            }
            if ui.button("Configurer…  Ctrl+R").clicked() {
                self.load_selected();
                self.open_run_popup();
            }
        }
        ui.add_space(12.0);
        ui.label(RichText::new("EXÉCUTIONS").small().weak());
        let mut selected = None;
        for session in self
            .sessions
            .iter()
            .rev()
            .filter(|session| session.view == view)
        {
            let label = format!("{}  {}", session.status_symbol(), session.name);
            if ui
                .selectable_label(self.selected_session == Some(session.id), label)
                .on_hover_text(format!("{}\n{}", session.root.display(), session.command))
                .clicked()
            {
                selected = Some(session.id);
            }
        }
        if let Some(id) = selected {
            self.selected_session = Some(id);
            self.requested_view = Some(view);
        }
        self.show_error(ui);
    }

    pub(super) fn show_bottom_content(&mut self, ui: &mut egui::Ui, view: BottomView) {
        if view == BottomView::Terminal {
            if let Some(request) =
                self.terminals
                    .show_bottom(ui, &self.worktree_id, &self.worktree_root)
            {
                self.run_requests.push_back(request);
            }
            self.show_error(ui);
            return;
        }
        ui.horizontal(|ui| {
            if view == BottomView::Terminal {
                let response = ui.add(
                    egui::TextEdit::singleline(&mut self.terminal_command)
                        .id_salt("terminal_command")
                        .hint_text("Commande dans le worktree actif…")
                        .desired_width((ui.available_width() - 110.0).max(100.0)),
                );
                let enter =
                    response.lost_focus() && ui.input(|input| input.key_pressed(egui::Key::Enter));
                if ui.button("Exécuter").clicked() || enter {
                    let command = self.terminal_command.trim().to_owned();
                    self.run_command(&command, &command, BottomView::Terminal);
                    if !command.is_empty() {
                        self.terminal_command.clear();
                    }
                    response.request_focus();
                }
            } else if ui.button("Configurations…  Ctrl+R").clicked() {
                self.open_run_popup();
            }
        });
        ui.horizontal_wrapped(|ui| {
            for session in self.sessions.iter().filter(|session| session.view == view) {
                let label = format!("{} {}", session.status_symbol(), session.name);
                if ui
                    .selectable_label(self.selected_session == Some(session.id), label)
                    .clicked()
                {
                    self.selected_session = Some(session.id);
                }
            }
        });
        self.show_error(ui);
        let index = self
            .selected_session
            .and_then(|id| {
                self.sessions
                    .iter()
                    .position(|session| session.id == id && session.view == view)
            })
            .or_else(|| {
                self.sessions
                    .iter()
                    .rposition(|session| session.view == view)
            });
        let Some(index) = index else {
            ui.add_space(8.0);
            ui.label(match view {
                BottomView::Terminal => "Les sorties apparaîtront ici. Cette console accepte des commandes et des lignes d’entrée ; les applications plein écran nécessitent un terminal externe.",
                BottomView::Tests => "Lancez une commande de test depuis le volet gauche ou Ctrl+R. Son résultat et son code de sortie apparaîtront ici.",
                BottomView::Run => "Ctrl+R pour choisir un script ou saisir une nouvelle commande.",
            });
            ui.label(
                RichText::new(self.worktree_root.display().to_string())
                    .small()
                    .weak(),
            );
            return;
        };
        let session = &mut self.sessions[index];
        ui.horizontal(|ui| {
            ui.label(RichText::new(session.status_text()).strong());
            ui.label(
                RichText::new(session.root.display().to_string())
                    .small()
                    .weak(),
            )
            .on_hover_text(format!(
                "Worktree : {}\n{}",
                session.worktree_id, session.command
            ));
            if session.is_running() && ui.small_button("Arrêter").clicked() {
                session.stop();
            }
            if ui.small_button("Copier").clicked() {
                ui.ctx().copy_text(session.output.clone());
            }
            if ui.small_button("Effacer").clicked() {
                session.output.clear();
                session.truncated = false;
            }
        });
        if session.is_running() {
            ui.horizontal(|ui| {
                let response = ui.add(
                    egui::TextEdit::singleline(&mut session.stdin)
                        .id_salt(("run_stdin", session.id))
                        .hint_text("Entrée standard…")
                        .desired_width((ui.available_width() - 180.0).max(100.0)),
                );
                let enter =
                    response.lost_focus() && ui.input(|input| input.key_pressed(egui::Key::Enter));
                if ui.button("Envoyer").clicked() || enter {
                    let line = std::mem::take(&mut session.stdin);
                    let _ = session.control.send(Control::Input(format!("{line}\n")));
                    response.request_focus();
                }
                if ui
                    .button("Fin d’entrée")
                    .on_hover_text("Fermer stdin (EOF)")
                    .clicked()
                {
                    let _ = session.control.send(Control::CloseInput);
                }
            });
        }
        if session.truncated {
            ui.label(
                RichText::new("Début du journal retiré : affichage limité au dernier Mio.")
                    .small()
                    .weak(),
            );
        }
        ui.separator();
        egui::ScrollArea::both()
            .id_salt(("run_output", session.id))
            .auto_shrink([false, false])
            .stick_to_bottom(true)
            .show(ui, |ui| {
                ui.add(
                    egui::Label::new(RichText::new(&session.output).monospace()).selectable(true),
                );
            });
    }

    pub(super) fn show_run_popup(&mut self, ctx: &egui::Context) {
        if !self.popup_open {
            return;
        }
        let mut open = true;
        let mut close = false;
        egui::Window::new("Exécuter une commande")
            .id(egui::Id::new("run_configuration_popup"))
            .open(&mut open)
            .collapsible(false)
            .default_width(680.0)
            .show(ctx, |ui| {
                ui.label(
                    RichText::new(self.worktree_root.display().to_string())
                        .small()
                        .weak(),
                );
                let mut selected = None;
                egui::ComboBox::from_id_salt("run_configuration_picker")
                    .width(430.0)
                    .selected_text(
                        self.configurations
                            .get(self.selected_config)
                            .map_or("Nouvelle commande", |configuration| {
                                configuration.name.as_str()
                            }),
                    )
                    .show_ui(ui, |ui| {
                        for (index, configuration) in self.configurations.iter().enumerate() {
                            if ui
                                .selectable_label(
                                    index == self.selected_config,
                                    &configuration.name,
                                )
                                .clicked()
                            {
                                selected = Some(index);
                            }
                        }
                    });
                if let Some(index) = selected {
                    self.selected_config = index;
                    self.load_selected();
                }
                if ui.button("Actualiser les scripts").on_hover_text("Détecter les dossiers de sources et leurs scripts Python, sans exécuter de code").clicked() {
                    self.refresh_scripts();
                }
                ui.add_space(8.0);
                ui.label("Nom");
                ui.add(
                    egui::TextEdit::singleline(&mut self.edit_name).desired_width(f32::INFINITY),
                );
                ui.label("Commande");
                let command_response = ui.add(
                    egui::TextEdit::singleline(&mut self.edit_command)
                        .id_salt("run_command_edit")
                        .font(egui::TextStyle::Monospace)
                        .hint_text("python -m mon_module --option")
                        .desired_width(f32::INFINITY),
                );
                if self.focus_command {
                    command_response.request_focus();
                    self.focus_command = false;
                }
                let directory = self.configurations.get(self.selected_config)
                    .and_then(|configuration| configuration.working_directory.as_deref())
                    .unwrap_or_else(|| Path::new("."));
                ui.label(
                    RichText::new(format!(
                        "Shell : {} · dossier de travail : {}",
                        if cfg!(windows) { "PowerShell" } else { "/bin/sh" },
                        self.worktree_root.join(directory).display(),
                    ))
                    .small()
                    .weak(),
                );
                ui.horizontal(|ui| {
                    ui.label("Afficher dans");
                    ui.selectable_value(&mut self.edit_view, BottomView::Run, "Exécution");
                    ui.selectable_value(&mut self.edit_view, BottomView::Tests, "Tests");
                });
                ui.add_space(8.0);
                ui.horizontal(|ui| {
                    if ui.button("Nouvelle").clicked() {
                        self.edit_name.clear();
                        self.edit_command.clear();
                        self.selected_config = self.configurations.len();
                        self.focus_command = true;
                    }
                    if ui.button("Enregistrer").clicked() {
                        self.save_edited();
                    }
                    if ui
                        .add_enabled(
                            self.selected_config < self.configurations.len(),
                            egui::Button::new("Supprimer"),
                        )
                        .clicked()
                    {
                        let mut updated = self.configurations.clone();
                        updated.remove(self.selected_config);
                        if self.persist(&updated) {
                            self.configurations = updated;
                            self.selected_config = 0;
                            self.load_selected();
                        }
                    }
                    let enter = command_response.lost_focus()
                        && ui.input(|input| input.key_pressed(egui::Key::Enter));
                    if ui.button("▶ Exécuter").clicked() || enter {
                        let name = if self.edit_name.trim().is_empty() {
                            self.edit_command.clone()
                        } else {
                            self.edit_name.clone()
                        };
                        let command = self.edit_command.clone();
                        let directory = self.configurations.get(self.selected_config)
                            .and_then(|configuration| configuration.working_directory.clone());
                        self.run_command_in_directory(&name, &command, self.edit_view, directory.as_deref());
                        close = !command.trim().is_empty() && self.error.is_none();
                    }
                });
                self.show_error(ui);
            });
        self.popup_open = open && !close;
    }

    fn load_selected(&mut self) {
        if let Some(configuration) = self.configurations.get(self.selected_config) {
            self.edit_name.clone_from(&configuration.name);
            self.edit_command.clone_from(&configuration.command);
            self.edit_view = configuration.view;
        } else {
            self.edit_name.clear();
            self.edit_command.clear();
            self.edit_view = BottomView::Run;
        }
    }

    fn refresh_scripts(&mut self) {
        (self.source_roots, self.primary_source_root) = discover_source_roots(&self.worktree_root);
        self.refresh_configurations();
    }

    fn refresh_configurations(&mut self) {
        let unedited_selection =
            self.configurations
                .get(self.selected_config)
                .is_some_and(|configuration| {
                    configuration.name == self.edit_name
                        && configuration.command == self.edit_command
                        && configuration.view == self.edit_view
                });
        let selected_name = self
            .configurations
            .get(self.selected_config)
            .map(|configuration| configuration.name.clone());
        refresh_generated_configs(
            &mut self.configurations,
            &self.worktree_root,
            &self.primary_source_root,
            &self.source_roots,
        );
        self.selected_config = if let Some(name) = selected_name {
            self.configurations
                .iter()
                .position(|configuration| configuration.name == name)
                .unwrap_or(0)
        } else {
            self.configurations.len()
        };
        if unedited_selection {
            self.load_selected();
        }
    }

    fn save_edited(&mut self) {
        if self.edit_name.trim().is_empty() || self.edit_command.trim().is_empty() {
            self.error = Some("Indiquez un nom et une commande pour cette configuration.".into());
            return;
        }
        let configuration = RunConfig {
            name: self.edit_name.trim().into(),
            command: self.edit_command.trim().into(),
            view: self.edit_view,
            working_directory: self
                .configurations
                .get(self.selected_config)
                .and_then(|configuration| configuration.working_directory.clone()),
            generated_command: self
                .configurations
                .get(self.selected_config)
                .filter(|configuration| {
                    configuration.name == self.edit_name.trim()
                        && configuration.command == self.edit_command.trim()
                        && configuration.view == self.edit_view
                })
                .and_then(|configuration| configuration.generated_command.clone()),
        };
        let mut updated = self.configurations.clone();
        let index = if self.selected_config < updated.len() {
            updated[self.selected_config] = configuration;
            self.selected_config
        } else {
            updated.push(configuration);
            updated.len() - 1
        };
        if self.persist(&updated) {
            self.configurations = updated;
            self.selected_config = index;
        }
    }

    fn persist(&mut self, configurations: &[RunConfig]) -> bool {
        match write_configs(&self.config_path, configurations) {
            Ok(()) => {
                self.error = None;
                true
            }
            Err(error) => {
                self.error = Some(format!("Enregistrement impossible : {error}"));
                false
            }
        }
    }

    fn show_error(&mut self, ui: &mut egui::Ui) {
        if let Some(error) = &self.error {
            ui.colored_label(ui.visuals().error_fg_color, error);
        }
    }
}

fn discover_source_roots(root: &Path) -> (Vec<PathBuf>, PathBuf) {
    match PythonProjectLayout::discover(root) {
        Ok(layout) => (layout.source_roots, layout.primary_source_root),
        Err(_) => (vec![PathBuf::from(".")], PathBuf::from(".")),
    }
}

fn command_in_directory(
    root: &Path,
    directory: Option<&Path>,
    command: &str,
) -> Result<String, String> {
    let Some(directory) = directory else {
        return Ok(command.to_owned());
    };
    if directory.components().any(|component| {
        !matches!(
            component,
            std::path::Component::Normal(_) | std::path::Component::CurDir
        )
    }) {
        return Err("Le dossier de lancement doit être relatif au worktree actif.".into());
    }
    if directory
        .components()
        .all(|component| component == std::path::Component::CurDir)
    {
        return Ok(command.to_owned());
    }
    let target = root.join(directory);
    if !target.is_dir()
        || !root.canonicalize().is_ok_and(|root| {
            target
                .canonicalize()
                .is_ok_and(|target| target.starts_with(root))
        })
    {
        return Err("Le dossier de sources n’est plus disponible dans le worktree actif.".into());
    }
    // Keep RunRequest.root at the worktree so save/sync validation retains its identity.
    let directory = quote_shell_argument(
        &format!("./{}", directory.to_string_lossy().replace('\\', "/")),
        cfg!(windows),
    );
    Ok(if cfg!(windows) {
        format!("Set-Location -LiteralPath {directory} -ErrorAction Stop; {command}")
    } else {
        format!("cd {directory} && {command}")
    })
}

fn python_interpreter_in_source_root(root: &Path, source_root: &Path) -> String {
    let Some(environment) = discover_python_environment(root, source_root) else {
        return if cfg!(windows) { "python" } else { "python3" }.into();
    };
    let source_components: Vec<_> = source_root
        .components()
        .filter(|component| *component != std::path::Component::CurDir)
        .collect();
    let interpreter_components: Vec<_> = environment
        .interpreter
        .components()
        .filter(|component| *component != std::path::Component::CurDir)
        .collect();
    let shared = source_components
        .iter()
        .zip(&interpreter_components)
        .take_while(|(source, interpreter)| source == interpreter)
        .count();
    let mut relative = PathBuf::from(".");
    for _ in shared..source_components.len() {
        relative.push("..");
    }
    for component in &interpreter_components[shared..] {
        relative.push(component.as_os_str());
    }
    let interpreter = quote_shell_argument(
        &relative.to_string_lossy().replace('\\', "/"),
        cfg!(windows),
    );
    if cfg!(windows) {
        format!("& {interpreter}")
    } else {
        interpreter
    }
}

