fn refresh_generated_configs(
    configurations: &mut Vec<RunConfig>,
    root: &Path,
    primary_source_root: &Path,
    source_roots: &[PathBuf],
) {
    let mut discovered = default_configs(root, primary_source_root);
    let default_count = discovered.len();
    append_discovered_scripts(&mut discovered, root, source_roots);
    configurations.retain_mut(|configuration| {
        if configuration.generated_command.as_ref() != Some(&configuration.command) {
            configuration.generated_command = None;
            return true;
        }
        if let Some(updated) = discovered
            .iter()
            .find(|updated| updated.name == configuration.name)
        {
            *configuration = updated.clone();
            true
        } else {
            false
        }
    });
    // Saved deletions of default launch configurations remain respected.
    for configuration in discovered.into_iter().skip(default_count) {
        if !configurations.iter().any(|existing| {
            existing.name == configuration.name
                || (existing.command == configuration.command
                    && existing.working_directory == configuration.working_directory)
        }) {
            configurations.push(configuration);
        }
    }
}

fn append_discovered_scripts(
    configurations: &mut Vec<RunConfig>,
    root: &Path,
    source_roots: &[PathBuf],
) {
    for configuration in source_roots
        .iter()
        .flat_map(|source_root| discover_scripts(root, source_root))
        .take(64)
    {
        if !configurations.iter().any(|existing| {
            existing.name == configuration.name
                || (existing.command == configuration.command
                    && existing.working_directory == configuration.working_directory)
        }) {
            configurations.push(configuration);
        }
    }
}

fn discover_scripts(root: &Path, source_root: &Path) -> Vec<RunConfig> {
    let Ok(canonical_root) = root.canonicalize() else {
        return Vec::new();
    };
    let source_directory = root.join(source_root);
    let mut scripts = Vec::new();
    for directory in [source_directory.clone(), source_directory.join("scripts")] {
        if !directory
            .canonicalize()
            .is_ok_and(|path| path.starts_with(&canonical_root))
        {
            continue;
        }
        let Ok(entries) = fs::read_dir(&directory) else {
            continue;
        };
        // Bound discovery even in a directory containing thousands of unrelated files.
        for entry in entries.take(4096).flatten() {
            if !entry.file_type().is_ok_and(|kind| kind.is_file()) {
                continue;
            }
            let path = entry.path();
            let Some(name) = path.file_name().and_then(|value| value.to_str()) else {
                continue;
            };
            if path.extension().is_none_or(|extension| extension != "py")
                || name == "manage.py"
                || name == "__init__.py"
                || name.starts_with("test_")
                || name.ends_with("_test.py")
                || name == "test.py"
                || name == "tests.py"
            {
                continue;
            }
            let Ok(relative) = path.strip_prefix(&source_directory) else {
                continue;
            };
            scripts.push(relative.to_string_lossy().replace('\\', "/"));
        }
    }
    scripts.sort();
    scripts.dedup();
    scripts.truncate(64);
    let interpreter = python_interpreter_in_source_root(root, source_root);
    scripts
        .into_iter()
        .map(|path| RunConfig {
            name: format!(
                "Python · {}",
                if source_root == Path::new(".") {
                    path.clone()
                } else {
                    source_root.join(&path).to_string_lossy().replace('\\', "/")
                }
            ),
            command: format!(
                "{interpreter} {}",
                quote_shell_argument(&format!("./{path}"), cfg!(windows))
            ),
            generated_command: Some(format!(
                "{interpreter} {}",
                quote_shell_argument(&format!("./{path}"), cfg!(windows))
            )),
            view: BottomView::Run,
            working_directory: Some(source_root.to_owned()),
        })
        .collect()
}

fn quote_shell_argument(argument: &str, windows: bool) -> String {
    if windows {
        format!("'{}'", argument.replace('\'', "''"))
    } else {
        format!("'{}'", argument.replace('\'', "'\"'\"'"))
    }
}

fn read_configs(path: &Path) -> Result<Option<Vec<RunConfig>>, String> {
    let data = match fs::read(path) {
        Ok(data) => data,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(error) => return Err(error.to_string()),
    };
    if data.len() > 1024 * 1024 {
        return Err("fichier de configurations trop volumineux".into());
    }
    let file: ConfigFile = serde_json::from_slice(&data).map_err(|error| error.to_string())?;
    if file.version != 1 {
        return Err(format!("version {} non prise en charge", file.version));
    }
    Ok(Some(file.configurations))
}

fn write_configs(path: &Path, configurations: &[RunConfig]) -> Result<(), String> {
    let directory = path.parent().ok_or("Dossier de configurations absent")?;
    fs::create_dir_all(directory).map_err(|error| error.to_string())?;
    let file = ConfigFile {
        version: 1,
        configurations: configurations.to_vec(),
    };
    let mut temporary =
        tempfile::NamedTempFile::new_in(directory).map_err(|error| error.to_string())?;
    serde_json::to_writer_pretty(&mut temporary, &file).map_err(|error| error.to_string())?;
    temporary
        .write_all(b"\n")
        .map_err(|error| error.to_string())?;
    temporary
        .as_file()
        .sync_all()
        .map_err(|error| error.to_string())?;
    temporary.persist(path).map_err(|error| error.to_string())?;
    Ok(())
}

enum Control {
    Input(String),
    CloseInput,
    Stop,
}

enum ProcessEvent {
    Started(u32),
    Output(String),
    Finished { code: Option<i32>, stopped: bool },
    Error(String),
}

struct RunSession {
    id: u64,
    name: String,
    command: String,
    view: BottomView,
    worktree_id: String,
    root: PathBuf,
    output: String,
    truncated: bool,
    stdin: String,
    started: Instant,
    elapsed: Option<Duration>,
    pid: Option<u32>,
    result: Option<(Option<i32>, bool)>,
    failed_to_start: bool,
    stopping: bool,
    control: Sender<Control>,
    events: Option<Receiver<ProcessEvent>>,
    worker: Option<JoinHandle<()>>,
}

impl RunSession {
    fn start(
        id: u64,
        name: String,
        command: String,
        view: BottomView,
        worktree_id: String,
        root: PathBuf,
    ) -> Self {
        let (control, controls) = mpsc::channel();
        let (events_sender, events) = mpsc::sync_channel(64);
        let worker_command = command.clone();
        let worker_root = root.clone();
        let worker = thread::spawn(move || {
            run_process(&worker_command, &worker_root, controls, events_sender)
        });
        Self {
            id,
            name,
            command: command.clone(),
            view,
            worktree_id,
            root,
            output: format!("$ {command}\n"),
            truncated: false,
            stdin: String::new(),
            started: Instant::now(),
            elapsed: None,
            pid: None,
            result: None,
            failed_to_start: false,
            stopping: false,
            control,
            events: Some(events),
            worker: Some(worker),
        }
    }

    fn is_running(&self) -> bool {
        self.result.is_none() && !self.failed_to_start
    }

    fn poll(&mut self) -> bool {
        let mut changed = false;
        for _ in 0..128 {
            let event = match self.events.as_ref().map(Receiver::try_recv) {
                Some(Ok(event)) => event,
                Some(Err(mpsc::TryRecvError::Disconnected)) if self.is_running() => {
                    self.failed_to_start = true;
                    self.elapsed = Some(self.started.elapsed());
                    self.append_output("\nLe canal de la commande a été fermé.\n");
                    changed = true;
                    break;
                }
                _ => break,
            };
            changed = true;
            match event {
                ProcessEvent::Started(pid) => self.pid = Some(pid),
                ProcessEvent::Output(text) => self.append_output(&text),
                ProcessEvent::Finished { code, stopped } => {
                    self.result = Some((code, stopped));
                    self.elapsed = Some(self.started.elapsed());
                }
                ProcessEvent::Error(message) => {
                    self.append_output(&format!("\n{message}\n"));
                    if self.pid.is_none() {
                        self.failed_to_start = true;
                        self.elapsed = Some(self.started.elapsed());
                    }
                }
            }
        }
        changed
    }

    fn append_output(&mut self, text: &str) {
        self.output.push_str(text);
        if self.output.len() > OUTPUT_LIMIT {
            let mut keep_from = self.output.len() - OUTPUT_LIMIT;
            while !self.output.is_char_boundary(keep_from) {
                keep_from += 1;
            }
            self.output.drain(..keep_from);
            self.truncated = true;
        }
    }

    fn stop(&mut self) {
        if self.is_running() {
            let _ = self.control.send(Control::Stop);
            self.stopping = true;
        }
    }

    fn status_symbol(&self) -> &'static str {
        match self.result {
            Some((_, true)) => "■",
            Some((Some(0), false)) => "✓",
            Some(_) => "×",
            None if self.failed_to_start => "!",
            None => "●",
        }
    }

    fn status_text(&self) -> String {
        let seconds = self
            .elapsed
            .unwrap_or_else(|| self.started.elapsed())
            .as_secs_f32();
        let status = match self.result {
            Some((_, true)) => "Arrêté".to_owned(),
            Some((Some(0), false)) if self.view == BottomView::Tests => {
                "Commande de test réussie · code 0".to_owned()
            }
            Some((Some(0), false)) => "Terminé · code 0".to_owned(),
            Some((Some(code), false)) => format!("Échec · code {code}"),
            Some((None, false)) => "Terminé par un signal".to_owned(),
            None if self.failed_to_start => "Lancement impossible".to_owned(),
            None if self.stopping => "Arrêt en cours…".to_owned(),
            None => "En cours".to_owned(),
        };
        format!("{status} · {seconds:.1} s")
    }
}

impl Drop for RunSession {
    fn drop(&mut self) {
        let _ = self.control.send(Control::Stop);
        // Unblock readers before waiting for shutdown, even with a full output queue.
        self.events.take();
        if let Some(worker) = self.worker.take() {
            let _ = worker.join();
        }
    }
}

fn shell_command(command: &str, root: &Path) -> Command {
    #[cfg(windows)]
    let mut process = {
        use std::os::windows::process::CommandExt;
        let mut process = Command::new("powershell.exe");
        process.args(["-NoLogo", "-NoProfile", "-NonInteractive", "-Command"]);
        // Native commands propagate their exit status. PowerShell errors set $? false.
        process.arg(format!("[Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false); $OutputEncoding = [Console]::OutputEncoding; $global:LASTEXITCODE = 0; & {{\n{command}\n}}; if (-not $?) {{ if ($LASTEXITCODE -ne 0) {{ exit $LASTEXITCODE }}; exit 1 }}; exit $LASTEXITCODE"));
        process.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
        process
    };
    #[cfg(unix)]
    let mut process = {
        use std::os::unix::process::CommandExt;
        let mut process = Command::new("/bin/sh");
        process.args(["-c", command]);
        process.process_group(0);
        process
    };
    process
        .current_dir(root)
        .env("PYTHONUNBUFFERED", "1")
        .env("PYTHONIOENCODING", "utf-8")
        .env("NO_COLOR", "1")
        .env("TERM", "dumb")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    process
}

fn run_process(
    command: &str,
    root: &Path,
    controls: Receiver<Control>,
    events: SyncSender<ProcessEvent>,
) {
    let mut child = match shell_command(command, root).spawn() {
        Ok(child) => child,
        Err(error) => {
            let _ = events.send(ProcessEvent::Error(format!(
                "Impossible de lancer la commande : {error}"
            )));
            return;
        }
    };
    let _ = events.send(ProcessEvent::Started(child.id()));
    let mut input = child.stdin.take().map(|mut stdin| {
        let (sender, receiver) = mpsc::sync_channel::<String>(16);
        let events = events.clone();
        // A program that does not read stdin must not block the supervisor's Stop action.
        thread::spawn(move || {
            while let Ok(text) = receiver.recv() {
                if let Err(error) = stdin
                    .write_all(text.as_bytes())
                    .and_then(|()| stdin.flush())
                {
                    let _ = events.send(ProcessEvent::Error(format!("Entrée standard : {error}")));
                    break;
                }
            }
        });
        sender
    });
    let (reader_done, readers_done) = mpsc::channel();
    for pipe in [
        child
            .stdout
            .take()
            .map(|pipe| Box::new(pipe) as Box<dyn Read + Send>),
        child
            .stderr
            .take()
            .map(|pipe| Box::new(pipe) as Box<dyn Read + Send>),
    ]
    .into_iter()
    .flatten()
    {
        let sender = events.clone();
        let done = reader_done.clone();
        thread::spawn(move || {
            stream_output(pipe, sender);
            let _ = done.send(());
        });
    }
    drop(reader_done);
    let mut stopped = false;
    let result = loop {
        match controls.recv_timeout(Duration::from_millis(40)) {
            Ok(Control::Input(text)) => {
                if text.len() > 64 * 1024 {
                    let _ = events.send(ProcessEvent::Error(
                        "L’entrée dépasse 64 Kio ; envoyez-la en plusieurs lignes.".into(),
                    ));
                } else if let Some(stdin) = &input {
                    match stdin.try_send(text) {
                        Ok(()) => {}
                        Err(mpsc::TrySendError::Full(_)) => {
                            let _ = events.send(ProcessEvent::Error("Le programme ne lit pas assez vite son entrée ; cette ligne n’a pas été envoyée.".into()));
                        }
                        Err(mpsc::TrySendError::Disconnected(_)) => {
                            input = None;
                            let _ = events
                                .send(ProcessEvent::Error("L’entrée standard est fermée.".into()));
                        }
                    }
                }
            }
            Ok(Control::CloseInput) => input = None,
            Ok(Control::Stop) | Err(mpsc::RecvTimeoutError::Disconnected) => {
                stopped = true;
                input = None;
                terminate_tree(&mut child);
            }
            Err(mpsc::RecvTimeoutError::Timeout) => {}
        }
        match child.try_wait() {
            Ok(Some(status)) => break Some(status),
            Ok(None) => {}
            Err(error) => {
                let _ = events.send(ProcessEvent::Error(format!("Suivi du processus : {error}")));
                terminate_tree(&mut child);
                break child.wait().ok();
            }
        }
    };
    drop(input);
    // Normal children close both pipes; background descendants must not hold the UI forever.
    let deadline = Instant::now() + Duration::from_millis(600);
    while let Some(remaining) = deadline.checked_duration_since(Instant::now()) {
        match readers_done.recv_timeout(remaining) {
            Ok(()) => {}
            Err(_) => break,
        }
    }
    let _ = events.send(ProcessEvent::Finished {
        code: result.and_then(|status| status.code()),
        stopped,
    });
}

fn terminate_tree(child: &mut Child) {
    if !matches!(child.try_wait(), Ok(None)) {
        return;
    }
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        let _ = Command::new("taskkill.exe")
            .args(["/PID", &child.id().to_string(), "/T", "/F"])
            .creation_flags(0x0800_0000)
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status();
    }
    #[cfg(unix)]
    {
        // shell_command created this process group, so no unrelated shell is signalled.
        let group = -(child.id() as i32);
        unsafe {
            libc::kill(group, libc::SIGKILL);
        }
    }
    let _ = child.kill();
}

fn stream_output(mut reader: impl Read, events: SyncSender<ProcessEvent>) {
    let mut buffer = [0_u8; 4096];
    let mut decoder = OutputDecoder::default();
    loop {
        match reader.read(&mut buffer) {
            Ok(0) => break,
            Ok(length) => {
                let output = decoder.push(&buffer[..length], false);
                if !output.is_empty() && events.send(ProcessEvent::Output(output)).is_err() {
                    return;
                }
            }
            Err(error) if error.kind() == std::io::ErrorKind::Interrupted => continue,
            Err(error) => {
                let _ = events.send(ProcessEvent::Error(format!(
                    "Lecture de la sortie : {error}"
                )));
                break;
            }
        }
    }
    let output = decoder.push(&[], true);
    if !output.is_empty() {
        let _ = events.send(ProcessEvent::Output(output));
    }
}

/// Preserves UTF-8 split across reads and removes ANSI controls across chunk boundaries.
#[derive(Default)]
struct OutputDecoder {
    pending: Vec<u8>,
    escape: u8,
}

impl OutputDecoder {
    fn push(&mut self, bytes: &[u8], finish: bool) -> String {
        self.pending.extend_from_slice(bytes);
        let mut text = String::new();
        loop {
            match std::str::from_utf8(&self.pending) {
                Ok(valid) => {
                    text.push_str(valid);
                    self.pending.clear();
                    break;
                }
                Err(error) => {
                    let valid = error.valid_up_to();
                    text.push_str(
                        std::str::from_utf8(&self.pending[..valid]).expect("UTF-8 prefix checked"),
                    );
                    self.pending.drain(..valid);
                    if let Some(invalid) = error.error_len() {
                        text.push('\u{fffd}');
                        self.pending.drain(..invalid);
                    } else {
                        if finish {
                            text.push_str(&String::from_utf8_lossy(&self.pending));
                            self.pending.clear();
                        }
                        break;
                    }
                }
            }
        }
        let mut output = String::new();
        for ch in text.chars() {
            match self.escape {
                0 if ch == '\u{1b}' => self.escape = 1,
                0 if !ch.is_control() || ch == '\n' || ch == '\t' => output.push(ch),
                1 if ch == '[' => self.escape = 2,
                1 if ch == ']' => self.escape = 3,
                1 => self.escape = 0,
                2 if ('@'..='~').contains(&ch) => self.escape = 0,
                3 if ch == '\u{7}' => self.escape = 0,
                3 if ch == '\u{1b}' => self.escape = 4,
                4 if ch == '\\' => self.escape = 0,
                4 => self.escape = 3,
                _ => {}
            }
        }
        output
    }
}

